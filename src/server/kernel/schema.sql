-- FTS5 unicode61 used no stemming or stop words and removed diacritics. Keep those
-- properties with simple plus unaccent. Prefixes become to_tsquery(..., 'pass:*').
CREATE EXTENSION IF NOT EXISTS unaccent WITH SCHEMA public;
CREATE TEXT SEARCH CONFIGURATION mainworthy_search (COPY = pg_catalog.simple);
ALTER TEXT SEARCH CONFIGURATION mainworthy_search
 ALTER MAPPING FOR hword, hword_part, word WITH public.unaccent, pg_catalog.simple;

CREATE TABLE search_docs (
 id bigint PRIMARY KEY,
 title text,
 body text,
 tags text,
 project bigint NOT NULL,
 tsv tsvector NOT NULL,
 title_tsv tsvector NOT NULL
);

CREATE FUNCTION search_docs_vector_fn() RETURNS trigger LANGUAGE plpgsql AS $trigger$
BEGIN
 NEW.title_tsv := to_tsvector('mainworthy_search', coalesce(NEW.title, ''));
 NEW.tsv := setweight(NEW.title_tsv, 'A') ||
  setweight(to_tsvector('mainworthy_search', coalesce(NEW.tags, '')), 'B') ||
  setweight(to_tsvector('mainworthy_search', coalesce(NEW.body, '')), 'D');
 RETURN NEW;
END;
$trigger$;
CREATE TRIGGER search_docs_vector BEFORE INSERT OR UPDATE ON search_docs
 FOR EACH ROW EXECUTE FUNCTION search_docs_vector_fn();
CREATE INDEX search_docs_tsv ON search_docs USING gin (tsv);
CREATE INDEX search_docs_title_tsv ON search_docs USING gin (title_tsv);
