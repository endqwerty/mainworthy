/** Historical SQLite audit only. Runtime code never imports bun:sqlite.
 * bun scripts/port-schema.ts > <scratch>/first.sql
 * MAINWORTHY_TEST_PG=postgres://... bun scripts/port-schema.ts --check
 * The pinned revision keeps this rerunnable after the SQLite chain is deleted.
 * A shallow clone first needs: git fetch origin 6f8bd211af19b732fcfa6ab7787969a51537c254
 */
import { Database as SQLite } from "bun:sqlite";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { SQL } from "bun";

export const SQLITE_REVISION = "6f8bd211af19b732fcfa6ab7787969a51537c254";
const root = fileURLToPath(new URL("../", import.meta.url));
const migrationPath = "src/server/kernel/migrations/";
type ObjectRow = { type: string; name: string; tbl_name: string; sql: string };

function git(...args: string[]): string {
	const result = Bun.spawnSync(["git", ...args], { cwd: root });
	if (result.exitCode !== 0) throw new Error(result.stderr.toString());
	return result.stdout.toString();
}

export function sqliteSchema(): ObjectRow[] {
	const files = git("ls-tree", "--name-only", `${SQLITE_REVISION}:${migrationPath.slice(0, -1)}`)
		.trim()
		.split("\n")
		.filter((name) => /^\d{4}_.*\.sql$/.test(name))
		.sort();
	if (files.length !== 43) throw new Error(`Expected 43 SQLite migrations, found ${files.length}`);
	const db = new SQLite(":memory:");
	try {
		for (const name of files) db.exec(git("show", `${SQLITE_REVISION}:${migrationPath}${name}`));
		return db
			.query<ObjectRow, []>("SELECT type,name,tbl_name,sql FROM sqlite_master WHERE sql IS NOT NULL ORDER BY type,name")
			.all();
	} finally {
		db.close();
	}
}

export function firstTranslation(): string {
	const objects = sqliteSchema();
	const references: string[] = [];
	const tables = objects.filter((row) => row.type === "table" && !row.name.startsWith("search_docs"));
	const translated = tables.map((row) => {
		let text = row.sql.replace(/--[^\n]*/g, "").replace(/\s*STRICT(?:,\s*WITHOUT ROWID)?\s*$/i, "");
		text = text
			.replace(/\bINTEGER\b/g, "bigint")
			.replace(/\bid bigint PRIMARY KEY\b/g, "id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");
		text = text
			.replace(/length\(CAST\((\w+) AS BLOB\)\)/g, "octet_length($1)")
			.replace(/json_valid\((\w+)\)/g, "($1 IS JSON)");
		// Cycles and forward references require adding foreign keys after all tables exist.
		text = text.replace(
			/\b(\w+)(\s+bigint[^,\n]*?)\s+REFERENCES (\w+)\s*\((\w+)\)( ON DELETE CASCADE)?/g,
			(_, column: string, declaration: string, target: string, key: string, action: string | undefined) => {
				references.push(
					`ALTER TABLE ${row.name} ADD FOREIGN KEY (${column}) REFERENCES ${target} (${key})${action ?? ""} DEFERRABLE INITIALLY IMMEDIATE;`,
				);
				return `${column}${declaration}`;
			},
		);
		return `${text};`;
	});
	translated.push(
		"CREATE TABLE search_docs (id bigint PRIMARY KEY, title text, body text, tags text, project bigint NOT NULL);",
	);
	const indexes = objects
		.filter((row) => row.type === "index" && !row.name.startsWith("search_docs_"))
		.map(
			(row) =>
				`${row.sql.replaceAll("result/32", "(result/32)").replaceAll("json_extract(accepts, '$.commit')", "((accepts::jsonb)->>'commit')")};`,
		);
	const triggers = objects
		.filter((row) => row.type === "trigger")
		.map((row) => {
			const parts =
				/^CREATE TRIGGER (\w+) AFTER ([\s\S]+?) ON (\w+)(?:\s+WHEN ([\s\S]+?))?\s+BEGIN\s+([\s\S]+)\s*END$/i.exec(
					row.sql,
				);
			if (!parts) throw new Error(`Cannot translate trigger ${row.name}`);
			const [, name, event, table, condition, body] = parts;
			const when = condition?.replace(/\bIS NOT\b(?! NULL)/g, "IS DISTINCT FROM");
			const returns = event?.startsWith("DELETE") ? "OLD" : "NEW";
			return `CREATE FUNCTION ${name}_fn() RETURNS trigger LANGUAGE plpgsql AS $trigger$\nBEGIN\n${when ? ` IF ${when} THEN\n` : ""}${body}${when ? "\n END IF;" : ""}\n RETURN ${returns};\nEND;\n$trigger$;\nCREATE TRIGGER ${name} AFTER ${event} ON ${table} FOR EACH ROW EXECUTE FUNCTION ${name}_fn();`;
		});
	return `-- First translation of all 43 SQLite migrations at ${SQLITE_REVISION}.\n-- Generated by bun scripts/port-schema.ts; schema.sql is the reviewed baseline.\n\n${[...translated, ...references, ...indexes, ...triggers].join("\n\n")}\n`;
}

export type CatalogRow = { kind: string; name: string; definition: string };

/** Stable logical schema, excluding sequence internals and database/schema OIDs. */
export async function schemaCatalog(db: Pick<SQL, "unsafe">): Promise<CatalogRow[]> {
	return db.unsafe<CatalogRow[]>(`
SELECT 'table' AS kind,c.relname AS name,'' AS definition FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
 WHERE n.nspname=current_schema() AND c.relkind='r'
UNION ALL
SELECT 'column',c.relname||'.'||a.attname,
 format_type(a.atttypid,a.atttypmod)||CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE ' NULL' END||
 CASE WHEN a.attidentity<>'' THEN ' IDENTITY '||a.attidentity::text ELSE '' END||
 CASE WHEN d.oid IS NOT NULL THEN ' DEFAULT '||pg_get_expr(d.adbin,d.adrelid) ELSE '' END
 FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid JOIN pg_namespace n ON n.oid=c.relnamespace
 LEFT JOIN pg_attrdef d ON d.adrelid=c.oid AND d.adnum=a.attnum
 WHERE n.nspname=current_schema() AND c.relkind='r' AND a.attnum>0 AND NOT a.attisdropped
UNION ALL
SELECT 'constraint',c.relname||'.'||k.conname,pg_get_constraintdef(k.oid)
 FROM pg_constraint k JOIN pg_class c ON c.oid=k.conrelid JOIN pg_namespace n ON n.oid=c.relnamespace
 WHERE n.nspname=current_schema()
UNION ALL
SELECT 'index',i.relname,pg_get_indexdef(i.oid)
 FROM pg_index x JOIN pg_class i ON i.oid=x.indexrelid JOIN pg_namespace n ON n.oid=i.relnamespace
 WHERE n.nspname=current_schema()
UNION ALL
SELECT 'trigger',c.relname||'.'||t.tgname,pg_get_triggerdef(t.oid)
 FROM pg_trigger t JOIN pg_class c ON c.oid=t.tgrelid JOIN pg_namespace n ON n.oid=c.relnamespace
 WHERE n.nspname=current_schema() AND NOT t.tgisinternal
UNION ALL
SELECT DISTINCT 'function',p.proname,pg_get_functiondef(p.oid)
 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace JOIN pg_trigger t ON t.tgfoid=p.oid
 WHERE n.nspname=current_schema() AND NOT t.tgisinternal
ORDER BY kind,name`);
}

// Each deliberate hand edit is named, not a wildcard exemption for a class of changes.
export const HAND_EDITS = new Map([
	[
		"function:search_docs_vector_fn",
		`CREATE OR REPLACE FUNCTION search_docs_vector_fn()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
DECLARE
 body_prefix text := coalesce(NEW.body, '');
 lower_chars integer := 0;
 upper_chars integer := 65536;
 middle_chars integer;
 parts text[];
 part integer := 1;
 vector tsvector;
 vectors tsvector[] := ARRAY[]::tsvector[];
BEGIN
 -- Keep a UTF-8 character boundary within the first 64 KiB of the body.
 IF octet_length(body_prefix) > 65536 THEN
  WHILE lower_chars < upper_chars LOOP
   middle_chars := (lower_chars + upper_chars + 1) / 2;
   IF octet_length(left(body_prefix, middle_chars)) <= 65536 THEN
    lower_chars := middle_chars;
   ELSE
    upper_chars := middle_chars - 1;
   END IF;
  END LOOP;
  body_prefix := left(body_prefix, lower_chars);
 END IF;
 -- Three vectors of at most 256 KiB stay below tsvector's 1 MiB limit when joined.
 -- Normal titles and tags remain whole; oversized fields retain a searchable prefix.
 parts := ARRAY[coalesce(NEW.title, ''), coalesce(NEW.tags, ''), body_prefix];
 WHILE part <= 3 LOOP
  BEGIN
   WHILE part <= 3 LOOP
    vector := to_tsvector('mainworthy_search', parts[part]);
    IF pg_column_size(vector) > 262144 THEN EXIT; END IF;
    vectors := array_append(vectors, vector);
    part := part + 1;
   END LOOP;
  EXCEPTION WHEN program_limit_exceeded THEN
   NULL;
  END;
  IF part <= 3 THEN
   parts[part] := left(parts[part], char_length(parts[part]) / 2);
  END IF;
 END LOOP;
 NEW.title_tsv := vectors[1];
 NEW.tsv := setweight(vectors[1], 'A') || setweight(vectors[2], 'B') || setweight(vectors[3], 'D');
 RETURN NEW;
END;
$function$
`,
	],
	["column:handoffs.queue_order", "bigint NOT NULL IDENTITY d"],
	["constraint:handoffs.handoffs_queue_order_not_null", "NOT NULL queue_order"],
	["constraint:search_docs.search_docs_tsv_not_null", "NOT NULL tsv"],
	["constraint:search_docs.search_docs_title_tsv_not_null", "NOT NULL title_tsv"],
	["index:handoffs_order", "CREATE UNIQUE INDEX handoffs_order ON handoffs USING btree (queue_order)"],
	["column:search_docs.tsv", "tsvector NOT NULL"],
	["column:search_docs.title_tsv", "tsvector NOT NULL"],
	["index:search_docs_tsv", "CREATE INDEX search_docs_tsv ON search_docs USING gin (tsv)"],
	["index:search_docs_title_tsv", "CREATE INDEX search_docs_title_tsv ON search_docs USING gin (title_tsv)"],
	[
		"trigger:search_docs.search_docs_vector",
		"CREATE TRIGGER search_docs_vector BEFORE INSERT OR UPDATE ON search_docs FOR EACH ROW EXECUTE FUNCTION search_docs_vector_fn()",
	],
]);

async function check(): Promise<void> {
	const url = process.env.MAINWORTHY_TEST_PG ?? process.env.MAINWORTHY_DATABASE_URL;
	if (!url)
		throw new Error(
			"--check needs MAINWORTHY_TEST_PG or MAINWORTHY_DATABASE_URL (a disposable PostgreSQL 18 database)",
		);
	const pool = new SQL(url, { max: 1 });
	const db = await pool.reserve();
	try {
		await db.unsafe("BEGIN");
		const catalogs: CatalogRow[][] = [];
		for (const { name, text } of [
			{ name: "port_generated", text: firstTranslation() },
			{
				name: "port_reviewed",
				text: readFileSync(new URL("../src/server/kernel/schema.sql", import.meta.url), "utf8"),
			},
		]) {
			await db.unsafe(`CREATE SCHEMA ${name}; SET LOCAL search_path TO ${name}, public`);
			await db.unsafe(text);
			catalogs.push(
				(await schemaCatalog(db)).map((row) => ({ ...row, definition: row.definition.replaceAll(`${name}.`, "") })),
			);
		}
		const [before = [], after = []] = catalogs;
		const expected = new Map(before.map((row) => [`${row.kind}:${row.name}`, row.definition]));
		const found = new Map(after.map((row) => [`${row.kind}:${row.name}`, row.definition]));
		const differences: string[] = [];
		for (const [key, value] of expected)
			if (found.get(key) !== value) differences.push(`${key}: expected ${value}, found ${found.get(key)}`);
		for (const [key, value] of found) {
			if (expected.has(key)) continue;
			if (HAND_EDITS.get(key) !== value) differences.push(`${key}: unexpected addition ${value}`);
			else console.log(`Hand edit: ${key}: ${value}`);
		}
		for (const key of HAND_EDITS.keys()) if (!found.has(key)) differences.push(`Missing hand edit: ${key}`);
		if (differences.length) throw new Error(differences.join("\n"));
		console.log(
			`PASS: 43 SQLite migrations; ${before.length} catalog entries preserved; ${HAND_EDITS.size} justified hand edits only.`,
		);
	} finally {
		await db.unsafe("ROLLBACK");
		db.release();
		await pool.close();
	}
}

if (import.meta.main) {
	if (process.argv.includes("--check")) await check();
	else process.stdout.write(firstTranslation());
}
