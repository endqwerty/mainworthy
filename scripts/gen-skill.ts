import { z } from "zod";
import { MCP_OPS } from "../src/server/ops/index.ts";
import { mcpTools } from "../src/surfaces/mcp.ts";

type Schema = z.core.JSONSchema.JSONSchema;
type SchemaNode = z.core.JSONSchema._JSONSchema;

function schemaType(schema: SchemaNode): string {
	if (typeof schema === "boolean") return schema ? "unknown" : "never";
	if ("const" in schema) return JSON.stringify(schema.const);
	if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
	const choices = schema.anyOf ?? schema.oneOf;
	if (choices) return [...new Set(choices.map(schemaType))].join(" | ");
	if (schema.type === "array") {
		return `array<${schema.items && !Array.isArray(schema.items) ? schemaType(schema.items) : "unknown"}>`;
	}
	if (schema.type === "object" && typeof schema.additionalProperties === "object") {
		return `record<${schemaType(schema.additionalProperties)}>`;
	}
	return Array.isArray(schema.type) ? schema.type.join(" | ") : (schema.type ?? "unknown");
}

const cell = (text: string): string => text.replaceAll("|", "\\|").replaceAll("\n", " ");

/** One table row per input property, nested ones included. Also the input tables of the documentation (`gen-docs.ts`). */
export function rows(schema: Schema, prefix = "", envelope = true): string[] {
	const lines: string[] = [];
	for (const [name, property] of Object.entries(schema.properties ?? {})) {
		if (envelope && name === "cmd") continue;
		const path = prefix ? `${prefix}.${name}` : name;
		const description = typeof property === "boolean" ? "" : (property.description ?? "");
		const defaultValue =
			typeof property !== "boolean" && "default" in property
				? ` Default: \`${JSON.stringify(property.default)}\`.`
				: "";
		lines.push(
			`| \`${cell(path)}\` | \`${cell(schemaType(property))}\` | ${schema.required?.includes(name) ? "yes" : "no"} | ${cell(description + defaultValue)} |`,
		);
		if (typeof property === "boolean") continue;
		lines.push(...rows(property, path, false));
		if (property.items && !Array.isArray(property.items) && typeof property.items !== "boolean") {
			lines.push(...rows(property.items, `${path}[]`, false));
		}
	}
	for (const [index, choice] of (schema.anyOf ?? schema.oneOf ?? []).entries()) {
		const op = choice.properties?.op;
		const label = typeof op === "object" && typeof op.const === "string" ? op.const : String(index + 1);
		lines.push(...rows(choice, `${prefix}[${label}]`, envelope));
	}
	return lines;
}

/** Returns the registry's agent tool docs, including nested properties, without programmatic command ids. */
export function generateToolReference(): string {
	const lines = [
		"# Tools",
		"",
		"<!-- Generated by bun scripts/gen-skill.ts. Edit the registry, then run the generator. -->",
		"",
		"Each call returns compact JSON with `result` and `seq`. Errors return an error code and message with `isError: true`.",
		"",
		"`project` is required unless the instance has exactly one project. Nested rows show the fields within an array or choice.",
		"",
		"Choice labels such as `[create]` or `[1]` show which input shape a field belongs to. Send the fields for one choice.",
	];
	const tools = mcpTools();
	for (const op of MCP_OPS) {
		if (op.mcp === null) continue;
		const tool = tools.find((entry) => entry.name === op.name);
		if (!tool) throw new Error(`No agent tool for ${op.name}`);
		const project = z
			.object({ type: z.literal("string"), description: z.string().default("") })
			.parse(tool.inputSchema.properties?.project);
		const schema = z.toJSONSchema(op.input, { io: "input" });
		schema.properties = { ...schema.properties, project };
		lines.push(
			"",
			`## ${op.name}`,
			"",
			op.mcp,
			"",
			"| Property | Type | Required | Description |",
			"| --- | --- | --- | --- |",
			...rows(schema),
		);
	}
	return `${lines.join("\n")}\n`;
}

if (import.meta.main) {
	await Bun.write(new URL("../skill/mainworthy/references/tools.md", import.meta.url), generateToolReference());
}
